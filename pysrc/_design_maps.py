def build(left):
    """左半 15 列 + 镜像 -> 30x30 块图；再把三个敌人出生车道打通 2 块。"""
    rows = []
    for l in left:
        assert len(l) == 15, (len(l), l)
        rows.append(list(l + l[::-1]))
    # 【出生车道】三个敌人出生点分别在块列 2 / 15 / 28，出生点正下方必须能开出去。
    # tb_terrain 的 T16b 要求“出生点 + 20px”往上数 10 格（= 块行 0~2）都是空的，
    # 所以这里把块行 2~3 的 1~2 / 14~15 / 27~28 列掏空 —— 2 块宽的车道，
    # 正好接上相位条带里的纵向走廊，敌人一出生就能往下压。
    for by in (2, 3):
        for bx in (1, 2, 14, 15, 27, 28):
            rows[by][bx] = '.'
    rows = [''.join(r) for r in rows]
    for r in rows:
        assert len(r) == 30, (len(r), r)
    return rows


def density(rows):
    """砖/钢/河/树/空 各占 900 块里的百分比"""
    n = float(mg.BCOLS * mg.BROWS)
    out = []
    for ch, name in (('#', '砖'), ('S', '钢'), ('~', '河'),
                     ('T', '树'), ('.', '空')):
        cnt = sum(r.count(ch) for r in rows)
        out.append('%s %.1f%%' % (name, 100.0 * cnt / n))
    return ', '.join(out)


def main():
    # ！！！警告！！！
    # pysrc/maps/level*.txt 现在是【手工维护的真源】：第十二轮之后它们被逐行微调过，
    # 和本脚本 LEVELS 里的布局已经不是同一版（本脚本重跑会把那些微调全部覆盖掉，
    # 而且会改掉河道/浅滩的位置，tb_enemy 的 E14/E15 会立刻红）。
    # 只想校验当前 txt 的话请用 pysrc/gen_levels.py；确实要按本脚本重画地图时
    # 必须显式加 --overwrite。
    write = '--overwrite' in sys.argv[1:]
    if not write:
        print('[WARN] 只校验、不写盘：level*.txt 是手工维护的真源，'
              '重跑会覆盖它（确实要重画请加 --overwrite）')
    ok = True
    for lv in LEVELS:
        rows = build(lv['left'])
        print('=' * 70)
        print(lv['name'], '->', density(rows))
        mg.print_ascii(rows)
        mg.check_level(rows)
        cells = mg.expand(rows)
        errs, notes = mg.validate(cells)
        for n in notes:
            print('[INFO] ' + n)
        if errs:
            ok = False
            print('[ERROR]')
            for e in errs:
                print('  - ' + e)
            continue
        if not write:
            continue
        path = os.path.join(HERE, 'maps', lv['name'] + '.txt')
        with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(HEAD.format(name=lv['name'], title=lv['title'],
                                notes='\n'.join(';' + n for n in lv['notes'])))
            f.write('\n'.join(rows) + '\n')
        print('[OK] wrote ' + path)
    if not ok:
        sys.exit(1)


if __name__ == '__main__':
    main()

