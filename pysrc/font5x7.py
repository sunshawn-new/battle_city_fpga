def glyph_rows(ch):
    """返回 7 个 5 位整数（行 0 在上，bit4 = 最左列）；没有的字符当空格"""
    art = GLYPHS.get(ch.upper())
    if art is None:
        art = GLYPHS[' ']
    rows = [ln for ln in art.strip('\n').split('\n') if ln != '']
    assert len(rows) == 7, (ch, len(rows))
    out = []
    for ln in rows:
        assert len(ln) == 5, (ch, ln)
        v = 0
        for i, c in enumerate(ln):
            if c == '#':
                v |= 1 << (4 - i)
        out.append(v)
    return out


def glyph_packed(ch):
    """把 7 行打包成一个 35 位整数：行 i 占 bit[5i +: 5]"""
    v = 0
    for i, row in enumerate(glyph_rows(ch)):
        v |= row << (5 * i)
    return v
